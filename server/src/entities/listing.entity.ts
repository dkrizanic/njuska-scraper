export interface ListingEntityProps {
  id: number;
  njuskalo_id: string;
  url: string;
  title: string;
  category_name?: string | null;
  ad_tier?: string | null;
  price_eur?: number | null;
  price_per_m2_eur?: number | null;
  views_count?: number | null;
  seller_id?: number | null;
  seller_name?: string | null;
  seller_type?: string | null;
  seller_url?: string | null;
  location_summary?: string | null;
  county?: string | null;
  city?: string | null;
  neighborhood?: string | null;
  property_type?: string | null;
  living_area_m2?: number | null;
  land_area_m2?: number | null;
  rooms?: string | null;
  floor?: string | null;
  total_floors?: string | null;
  year_built?: number | null;
  year_renovated?: number | null;
  energy_class?: string | null;
  heating_type?: string | null;
  parking?: string | null;
  description?: string | null;
  attributes?: Record<string, any> | null;
  image_urls?: string[] | null;
  details_scraped?: boolean;
  first_seen_at?: Date | string;
  last_seen_at?: Date | string;
  published_at?: Date | string | null;
}

export class ListingEntity {
  public id: number;
  public njuskaloId: string;
  public url: string;
  public title: string;
  public categoryName?: string | null;
  public adTier?: string | null;
  public priceEur?: number | null;
  public pricePerM2Eur?: number | null;
  public viewsCount?: number | null;
  public sellerId?: number | null;
  public sellerName?: string | null;
  public sellerType?: string | null;
  public sellerUrl?: string | null;
  public locationSummary?: string | null;
  public county?: string | null;
  public city?: string | null;
  public neighborhood?: string | null;
  public propertyType?: string | null;
  public livingAreaM2?: number | null;
  public landAreaM2?: number | null;
  public rooms?: string | null;
  public floor?: string | null;
  public totalFloors?: string | null;
  public yearBuilt?: number | null;
  public yearRenovated?: number | null;
  public energyClass?: string | null;
  public heatingType?: string | null;
  public parking?: string | null;
  public description?: string | null;
  public attributes: Record<string, any>;
  public imageUrls: string[];
  public detailsScraped: boolean;
  public firstSeenAt: Date;
  public lastSeenAt: Date;
  public publishedAt?: Date | null;

  constructor(props: ListingEntityProps) {
    this.id = props.id;
    this.njuskaloId = props.njuskalo_id;
    this.url = props.url;
    this.title = props.title;
    this.categoryName = props.category_name;
    this.adTier = props.ad_tier;
    this.priceEur = props.price_eur != null ? Number(props.price_eur) : null;
    this.pricePerM2Eur = props.price_per_m2_eur != null ? Number(props.price_per_m2_eur) : null;
    this.viewsCount = props.views_count != null ? Number(props.views_count) : null;
    this.sellerId = props.seller_id;
    this.sellerName = props.seller_name;
    this.sellerType = props.seller_type;
    this.sellerUrl = props.seller_url;
    this.locationSummary = props.location_summary;
    this.county = props.county;
    this.city = props.city;
    this.neighborhood = props.neighborhood;
    this.propertyType = props.property_type;
    this.livingAreaM2 = props.living_area_m2 != null ? Number(props.living_area_m2) : null;
    this.landAreaM2 = props.land_area_m2 != null ? Number(props.land_area_m2) : null;
    this.rooms = props.rooms;
    this.floor = props.floor;
    this.totalFloors = props.total_floors;
    this.yearBuilt = props.year_built;
    this.yearRenovated = props.year_renovated;
    this.energyClass = props.energy_class;
    this.heatingType = props.heating_type;
    this.parking = props.parking;
    this.description = props.description;
    this.attributes = props.attributes || {};
    this.imageUrls = Array.isArray(props.image_urls) ? props.image_urls : [];
    this.detailsScraped = Boolean(props.details_scraped);
    this.firstSeenAt = props.first_seen_at ? new Date(props.first_seen_at) : new Date();
    this.lastSeenAt = props.last_seen_at ? new Date(props.last_seen_at) : new Date();
    this.publishedAt = props.published_at ? new Date(props.published_at) : null;
  }
}
